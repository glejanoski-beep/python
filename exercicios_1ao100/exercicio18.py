num1 = int(input("Digite o primeiro valor: "))
num2 = int(input("Digite o segundo valor: "))

if num1 > num2:
    print(f"Maior valor: {num1}")
elif num1 < num2:
    print(f"Maior valor: {num2}")
else:
    print(f"Valores são iguais")


