largura = float(input("Digite o valor da largura: "))
altura = float(input("Digite o valor da altura: "))

area = largura * altura
perimetro = 2 * (largura + altura)

print(f"Largura: {largura}")
print(f"Altura: {altura}\n")
print(f"Área: {area}")
print(f"Perímetro: {perimetro}\n")


