celcius = int(input("Digite a temperatura em Celcius para saber o equivalente a Fahrenheit: "))

fahrenheit = celcius * 9 / 5 + 32

print(f"Temperatura em °C: {celcius}")
print(f"Temperatura em °F: {fahrenheit}")

