# Qual número atende ao seuinte critéroio? Sua metade mais 7 é igual a 19
# Equação:
# (x / 2) + 7 = 19
# x / 2 = 19 - 7 
# x = 12 * 2 
# x = 24

numero = 24

# Verificação a condição

resultado = (numero / 2) + 7

print(f"O numero que antede ao criterio e {numero}")
print(f"Verificação: a metade de {numero} ({numero / 2}) mais 7 é {resultado}")